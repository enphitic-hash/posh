// Writes supabase/seed.sql from the app's sample data (src/data/seed.ts).
// Usage: npx tsx scripts/seed-sql.mjs
import { writeFileSync } from 'node:fs'
import { makeSeed } from '../src/data/seed.ts'
import { KINDS } from '../src/data/types.ts'
const db = makeSeed()
const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const rows = KINDS.flatMap((k) => Object.values(db[k]).map((r) => `(${q(k)}, ${q(r.id)}, ${q(JSON.stringify(r))}::jsonb)`))
let out = '-- Posh Passport sample data. Generated by scripts/seed-sql.mjs. Run after schema.sql.\n-- Resets the table to the starting demo state.\ndelete from public.posh_records;\n'
for (let i = 0; i < rows.length; i += 200) out += `insert into public.posh_records (kind, id, data) values\n${rows.slice(i, i + 200).join(',\n')};\n`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out)
console.log(`supabase/seed.sql: ${rows.length} records`)
