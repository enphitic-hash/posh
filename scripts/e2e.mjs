import { chromium } from './pw.mjs'
const OUT = process.argv[2]; const base = 'http://localhost:4173/'
const b = await chromium.launch()
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } })
const errs = []
const p = await ctx.newPage()
p.on('pageerror', (e) => errs.push(e.message))
const shot = (n) => p.screenshot({ path: `${OUT}/e2e_${n}.png` })
await p.goto(base + '#/app'); await p.waitForTimeout(800)
await shot('01_welcome')
await p.getByText('I rent a Posh home').click()
await p.getByRole('button', { name: 'Sign in' }).click(); await p.waitForTimeout(500)
await shot('02_home')
await p.getByRole('button', { name: 'Pay with Posh card' }).click(); await p.waitForTimeout(400)
await p.getByText('Hold your Posh card to the back').click(); await p.waitForTimeout(400)
await shot('03_nfc_sheet')
await p.getByRole('button', { name: "Nakato's Posh card" }).click(); await p.waitForTimeout(1200)
await shot('04_methods')
await p.getByRole('switch').click()
await p.getByRole('button', { name: /^Pay UGX/ }).click(); await p.waitForTimeout(300)
for (const k of ['1', '2', '3', '4']) await p.getByRole('button', { name: k, exact: true }).click()
await shot('05_momo_pin')
await p.getByRole('button', { name: 'Send' }).click(); await p.waitForTimeout(2600)
await shot('06_receipt')
await p.getByRole('button', { name: 'Done' }).click(); await p.waitForTimeout(400)
await shot('07_home_after_part')
// repair
await p.goto(base + '#/app/repairs/new'); await p.waitForTimeout(400)
await p.getByPlaceholder('e.g. Kitchen sink leaking').fill('Bathroom light flickering')
await p.getByText('Electrical', { exact: true }).click()
await p.getByRole('button', { name: 'Send to Posh' }).click(); await p.waitForTimeout(600)
await shot('08_repair')
// office in same browser
const o = await ctx.newPage(); o.on('pageerror', (e) => errs.push('office: ' + e.message))
await o.setViewportSize({ width: 1440, height: 900 })
await o.goto(base + '#/office'); await o.waitForTimeout(600)
await o.getByLabel('PIN').fill('2024'); await o.getByRole('button', { name: 'Sign in' }).click(); await o.waitForTimeout(800)
await o.screenshot({ path: `${OUT}/e2e_09_dash.png` })
await o.goto(base + '#/office/repairs'); await o.waitForTimeout(600)
await o.getByText('Bathroom light flickering').click(); await o.waitForTimeout(400)
await o.getByRole('button', { name: 'Assign and notify' }).click(); await o.waitForTimeout(500)
await o.screenshot({ path: `${OUT}/e2e_10_repairs.png` })
// cross-tab: the phone page should now show the booked repair
await p.goto(base + '#/app/repairs'); await p.waitForTimeout(500)
await shot('11_phone_repairs')
// buyer
await p.evaluate(() => { const s = JSON.parse(localStorage.getItem('posh.prefs.v1')); s.app = { role: 'buyer' }; localStorage.setItem('posh.prefs.v1', JSON.stringify(s)) })
await p.goto(base + '#/app/search'); await p.reload(); await p.waitForTimeout(800)
await shot('12_search')
await p.locator('text=3-bed apartment · Ntinda').first().click(); await p.waitForTimeout(400)
await shot('13_listing')
await p.getByRole('button', { name: 'Book a viewing on WhatsApp' }).click(); await p.waitForTimeout(300)
await p.getByLabel('Your name').fill('Brian Kato'); await p.getByLabel('Phone (WhatsApp)').fill('+256 772 111 222')
await p.getByRole('button', { name: /^Book / }).click(); await p.waitForTimeout(400)
await shot('14_booked')
await o.goto(base + '#/office/sales'); await o.waitForTimeout(500)
await o.getByRole('button', { name: 'Viewings' }).click(); await o.waitForTimeout(300)
await o.screenshot({ path: `${OUT}/e2e_15_viewings.png` })
await o.goto(base + '#/office/cards'); await o.waitForTimeout(500)
await o.getByRole('button', { name: 'Issue card' }).click(); await o.waitForTimeout(300)
await o.screenshot({ path: `${OUT}/e2e_16_issue.png` })
await o.goto(base + '#/office/passports/PP-KLA-0412'); await o.waitForTimeout(500)
await o.screenshot({ path: `${OUT}/e2e_17_passport.png`, fullPage: true })
await o.goto(base + '#/office/settings'); await o.waitForTimeout(400)
await o.getByRole('radio', { name: 'Dark' }).click(); await o.getByRole('radio', { name: /Extra large/ }).click(); await o.waitForTimeout(300)
await o.screenshot({ path: `${OUT}/e2e_18_settings.png` })
console.log(errs.length ? errs.join('\n') : 'no errors')
await b.close()
